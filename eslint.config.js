import js from '@eslint/js'
import globals from 'globals'
import reactHooks from 'eslint-plugin-react-hooks'
import reactRefresh from 'eslint-plugin-react-refresh'
import { defineConfig, globalIgnores } from 'eslint/config'

export default defineConfig([
  globalIgnores(['dist', 'design-preview.html']),

  {
    files: ['**/*.{js,jsx}'],
    extends: [js.configs.recommended, reactHooks.configs.flat.recommended, reactRefresh.configs.vite],
    languageOptions: {
      globals: globals.browser,
      parserOptions: { ecmaFeatures: { jsx: true } },
    },
    rules: {
      // Colocating a context provider with its own `use*` hook is standard
      // React practice and better architecture than splitting every provider
      // across two files. The cost is that editing one of these files does a
      // full reload instead of preserving state — a development nicety, not a
      // correctness issue — so this stays a warning rather than an error.
      'react-refresh/only-export-components': ['warn', { allowConstantExport: true }],
      // No varsIgnorePattern: an unused capitalised constant is dead code, and
      // exempting it by naming convention hides exactly that.
      'no-unused-vars': ['error', { argsIgnorePattern: '^_' }],
    },
  },

  {
    // Build and tooling config runs in Node, not the browser.
    files: ['*.config.js', 'scripts/**/*.js'],
    languageOptions: { globals: { ...globals.node } },
  },

  {
    // shadcn/ui primitives are generated by `npx shadcn add` and are meant to be
    // regenerable. Linting them into a different shape means every regeneration
    // reintroduces the same findings, so the two rules its codegen trips are
    // relaxed here rather than the files being hand-edited.
    files: ['src/components/ui/**/*.jsx'],
    rules: {
      'no-unused-vars': 'off',
      'react-refresh/only-export-components': 'off',
    },
  },
])
